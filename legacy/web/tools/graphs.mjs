import { writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { TALENT_GRAPH, RELIC_GRAPH } from '../src/content/graphs.ts';
import { generateGraphLayout } from '../src/shared/graph-layout.ts';

const directory = new URL('../src/generated/', import.meta.url);
await mkdir(directory, { recursive: true });
const talent = generateGraphLayout(TALENT_GRAPH);
const relic = generateGraphLayout(RELIC_GRAPH);
const output = `// Generated by tools/graphs.mjs from semantic content; do not hand-edit coordinates.\nimport type { GraphLayout } from '../contracts/graph.ts';\nexport const TALENT_LAYOUT: GraphLayout = ${JSON.stringify(talent)};\nexport const RELIC_LAYOUT: GraphLayout = ${JSON.stringify(relic)};\n`;
await writeFile(new URL('graph-layouts.ts', directory), output, 'utf8');
console.log(`Generated graph layouts: ${TALENT_GRAPH.nodes.length} talents, ${RELIC_GRAPH.nodes.length} relic graph nodes → ${fileURLToPath(directory)}`);
