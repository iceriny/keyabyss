import type { BuildPresentation } from '../../contracts/build-content.ts';

type Entry = readonly [id: string, name: string, concepts: string, description: string, drawback: string, requirements?: string];
const parse = (source: string): Entry[] => source.trim().split('\n').map(line => {
  const fields = line.trim().split('|');
  if (fields.length < 5 || fields.length > 6 || fields.slice(0, 5).some(field => !field.trim())) throw new Error('Incomplete build presentation entry');
  return fields as unknown as Entry;
});
const present = (entries: readonly Entry[]): Readonly<Record<string, BuildPresentation>> => {
  if (new Set(entries.map(entry => entry[0])).size !== entries.length) throw new Error('Duplicate build presentation ID');
  return Object.freeze(Object.fromEntries(entries.map(([id, name, concepts, description, drawback, requirements = '']) => [id, Object.freeze({
  id, name, description, drawback,
  requirements: Object.freeze(requirements ? requirements.split('；') : []),
  concepts: Object.freeze(concepts.split('·')),
})])));
};

